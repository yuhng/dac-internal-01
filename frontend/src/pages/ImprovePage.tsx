import { useQuery } from '@tanstack/react-query'
import { Link, useNavigate } from 'react-router-dom'
import { api } from '../api/client'
import type { Analysis, Change, ChangeType } from '../api/types'
import { Badge, EmptyState, ErrorAlert, PageHead } from '../components/ui'
import { applyChanges } from '../lib/applyChanges'
import { useApplication } from '../state/useApplication'
import { useToast } from '../state/useToast'

const TYPE_BADGE: Record<ChangeType, string> = {
  Grammar: 'bg-primary-weak text-primary',
  Wording: 'bg-warn-weak text-warn',
  Alignment: 'bg-success-weak text-success',
}

const DIFF = 'rounded-md px-2 py-1 font-mono text-[12.5px] break-words whitespace-pre-wrap'

function ChangeRow({ change, accepted, onToggle }: { change: Change; accepted: boolean; onToggle(checked: boolean): void }) {
  return (
    <label className="grid grid-cols-[auto_1fr] gap-2.5 rounded-lg border border-line p-3">
      <input type="checkbox" className="mt-[3px] size-4 accent-primary" checked={accepted} onChange={e => onToggle(e.target.checked)} />
      <div className="min-w-0">
        <div className="mb-1.5 flex flex-wrap items-center gap-1.5">
          <Badge className={TYPE_BADGE[change.type]}>{change.type}</Badge>
          <span className="text-[13px] text-muted">{change.labels.join(' · ')}</span>
        </div>
        <div className={`${DIFF} bg-danger-weak text-danger line-through`}>{change.before.trim()}</div>
        <div className={`${DIFF} mt-1 bg-success-weak text-success`}>{change.after.trim()}</div>
        {change.note && <div className="mt-1.5 text-xs text-warn">⚠ {change.note}</div>}
      </div>
    </label>
  )
}

function Preview({ original, improved }: { original: string; improved: string }) {
  const originalLines = original.split('\n')
  return (
    <div className="max-h-[620px] overflow-auto rounded-lg bg-surface-2 p-3.5 font-mono text-[12.5px] break-words whitespace-pre-wrap">
      {improved.split('\n').map((line, i) => (
        <div key={i} className={line !== originalLines[i] ? 'bg-success-weak text-success' : ''}>{line || ' '}</div>
      ))}
    </div>
  )
}

function Improvements({ analysis, changes }: { analysis: Analysis; changes: Change[] }) {
  const { selection, setSelection, updateDraft, runAnalysis } = useApplication()
  const toast = useToast()
  const navigate = useNavigate()

  const isAccepted = (c: Change) => selection[c.id] ?? c.acceptedByDefault
  const accepted = changes.filter(isAccepted)
  const improved = applyChanges(analysis.cv, accepted)
  const selectAll = (value: boolean) => setSelection(Object.fromEntries(changes.map(c => [c.id, value])))

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(improved)
      toast('Copied to clipboard')
    } catch {
      toast('Copy failed. Select the preview text manually.')
    }
  }

  const download = () => {
    const url = URL.createObjectURL(new Blob([improved], { type: 'text/plain' }))
    const link = document.createElement('a')
    link.href = url
    link.download = `${analysis.title ? `${analysis.title.replace(/\W+/g, '-').toLowerCase()}-` : ''}cv.txt`
    link.click()
    setTimeout(() => URL.revokeObjectURL(url), 1000)
    toast('Download started')
  }

  const rescore = () => {
    if (improved === analysis.cv) {
      toast('Select at least one edit first')
      return
    }
    updateDraft({ cv: improved })
    navigate('/score')
    runAnalysis({ title: analysis.title, company: analysis.company, jd: analysis.jd, cv: improved, cl: analysis.cl }, analysis.overall)
  }

  return (
    <>
      <PageHead
        title="Tailored CV Improvements"
        subtitle="Review suggested edits. Nothing changes until you apply it."
        actions={
          <>
            <button type="button" className="btn" onClick={() => selectAll(true)}>Accept all</button>
            <button type="button" className="btn" onClick={() => selectAll(false)}>Reject all</button>
          </>
        }
      />
      <div className="grid items-start gap-5 lg:grid-cols-2">
        <div className="card min-w-0">
          <div className="mb-2 flex items-center justify-between gap-2">
            <h2 className="font-semibold">Suggested edits for {analysis.title || 'this role'}</h2>
            <span className="flex-none text-xs text-muted">{accepted.length} of {changes.length} selected</span>
          </div>
          <p className="mb-3.5 text-[13px] text-muted">Generated by rule-based checks (simulated AI rewriting).</p>
          <div className="space-y-2.5">
            {changes.map(change => (
              <ChangeRow
                key={change.id}
                change={change}
                accepted={isAccepted(change)}
                onToggle={checked => setSelection({ ...selection, [change.id]: checked })}
              />
            ))}
          </div>
        </div>
        <div className="card min-w-0 lg:sticky lg:top-5">
          <div className="mb-2 flex items-center justify-between gap-2">
            <h2 className="font-semibold">Improved CV preview</h2>
            <span className="text-[13px] text-muted">Highlighted lines changed</span>
          </div>
          <Preview original={analysis.cv} improved={improved} />
          <div className="mt-[18px] flex flex-wrap justify-end gap-2">
            <button type="button" className="btn" onClick={copy}>Copy text</button>
            <button type="button" className="btn" onClick={download}>Download .txt</button>
            <button type="button" className="btn btn-primary" onClick={rescore}>Use this CV &amp; re-score</button>
          </div>
        </div>
      </div>
    </>
  )
}

function ImproveHead() {
  return <PageHead title="Tailored CV Improvements" subtitle="Review suggested edits. Nothing changes until you apply it." />
}

function ImprovementsLoader({ analysis }: { analysis: Analysis }) {
  const { data: changes, error } = useQuery({
    queryKey: ['improvements', analysis.id],
    queryFn: () => api.improvement.suggest(analysis),
    staleTime: Infinity,
  })

  if (error) return <><ImproveHead /><ErrorAlert>{error.message}</ErrorAlert></>
  if (!changes) return <><ImproveHead /><div className="card"><EmptyState title="Preparing suggestions"><p className="text-[13px]">Reviewing your CV against this job.</p></EmptyState></div></>
  if (!changes.length) {
    return (
      <>
        <ImproveHead />
        <div className="card">
          <EmptyState icon="✓" title="No suggested edits">
            <p className="text-[13px]">No grammar, wording or alignment issues were detected for this job.</p>
            <Link className="btn mt-4" to="/score">Back to score</Link>
          </EmptyState>
        </div>
      </>
    )
  }
  return <Improvements analysis={analysis} changes={changes} />
}

export function ImprovePage() {
  const { analysis } = useApplication()
  if (analysis) return <ImprovementsLoader analysis={analysis} />
  return (
    <>
      <ImproveHead />
      <div className="card">
        <EmptyState icon="✎" title="Score a CV first">
          <p className="text-[13px]">Improvements are tailored to a specific job description, so run an analysis before reviewing edits.</p>
          <Link className="btn btn-primary mt-4" to="/score">Go to Score</Link>
        </EmptyState>
      </div>
    </>
  )
}
